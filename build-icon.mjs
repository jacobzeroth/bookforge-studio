#!/usr/bin/env node
/*
 * Embeds assets/icon.svg into index.html as a base64 data-URI favicon.
 * Keeps the app and the single-file build free of external asset requests.
 *
 *   node build-icon.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const svg = await readFile(resolve(ROOT, "assets/icon.svg"), "utf8");
const data = "data:image/svg+xml;base64," + Buffer.from(svg, "utf8").toString("base64");

const START = "<!-- @icon:start — generated by build-icon.mjs -->";
const END = "<!-- @icon:end -->";
const block =
  START + "\n" +
  '<link rel="icon" type="image/svg+xml" href="' + data + '">\n' +
  '<link rel="apple-touch-icon" href="' + data + '">\n' +
  END;

const html = await readFile(resolve(ROOT, "index.html"), "utf8");
const existing = html.slice(html.indexOf(START), html.indexOf(END) + END.length);
const out = existing.length ? html.replace(existing, block) : html.replace("<title>", block + "\n<title>");
if (out === html && !existing.length) throw new Error("could not place the icon block in index.html");
await writeFile(resolve(ROOT, "index.html"), out, "utf8");
console.log("embedded icon (" + (data.length / 1024).toFixed(1) + " KB data URI) into index.html");
