#!/usr/bin/env node
/*
 * Bundles BookForge Studio into one self-contained HTML file.
 * Inlines css/styles.css and every js/*.js in document order.
 *
 *   node build-standalone.mjs [output]
 *   node build-standalone.mjs ../bookforge.html
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(ROOT, process.argv[2] || "../bookforge.html");

const html = await readFile(resolve(ROOT, "index.html"), "utf8");

const cssTag = /<link\s+rel="stylesheet"\s+href="([^"]+)"\s*>/i;
const cssMatch = html.match(cssTag);
if (!cssMatch) throw new Error("stylesheet link not found");
const cssPath = cssMatch[1].split("?")[0];
const css = await readFile(resolve(ROOT, cssPath), "utf8");

let out = html.replace(cssTag, () => "<style>\n" + css + "\n</style>");

const scriptRe = /<script\s+src="([^"]+)"\s*><\/script>/gi;
const sources = [...out.matchAll(scriptRe)].map((m) => m[1]);
if (!sources.length) throw new Error("no script tags found");

for (const src of sources) {
  const file = src.split("?")[0];
  const code = await readFile(resolve(ROOT, file), "utf8");
  if (code.includes("</script")) throw new Error(file + " contains </script and cannot be inlined verbatim");
  out = out.replace(
    new RegExp('<script\\s+src="' + file.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + '[^"]*"\\s*><\\/script>', "i"),
    () => '<script data-src="' + file + '">\n' + code + '\n</script>'
  );
}

out = out.replace(
  "<title>BookForge Studio</title>",
  "<title>BookForge Studio</title>\n<!-- Self-contained build: css/styles.css and js/*.js inlined. Generated by build-standalone.mjs. -->"
);

const headEnd = out.indexOf("<script");
const head = headEnd === -1 ? out : out.slice(0, headEnd);
const leftover = head.match(/<script\s+src=[^>]*>|<link\s+rel="stylesheet"[^>]*>/i);
if (leftover) throw new Error("external asset reference remains: " + leftover[0]);

await writeFile(OUT, out, "utf8");
console.log("wrote " + OUT + " (" + (out.length / 1024).toFixed(1) + " KB, " + sources.length + " scripts inlined)");
