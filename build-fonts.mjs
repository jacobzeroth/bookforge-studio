#!/usr/bin/env node
/*
 * Embeds the brand fonts (Playfair Display + Open Sans, latin subset) into
 * css/styles.css as base64 @font-face rules, so the app — and the single-file
 * standalone build — keep their identity with no network access.
 *
 *   node build-fonts.mjs           # fetch, embed, rewrite css/styles.css
 *   node build-fonts.mjs --check   # report what is embedded, change nothing
 *
 * The block is delimited by @fonts:start / @fonts:end so repeat runs replace it
 * instead of stacking duplicates. Family names are the Google Fonts ones.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const CSS_PATH = resolve(ROOT, "css/styles.css");
const CHECK = process.argv.includes("--check");
const START = "/* @fonts:start — generated by build-fonts.mjs, do not edit by hand */";
const END = "/* @fonts:end */";

const REQUEST =
  "https://fonts.googleapis.com/css2?family=Playfair+Display:ital,wght@0,400..900;1,400..900" +
  "&family=Open+Sans:wght@300..800&display=swap";

// A modern UA keeps Google on woff2 instead of legacy ttf.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) " +
  "Chrome/124.0.0.0 Safari/537.36";

const LATIN_HINT = "U+0000-00FF";

function parseFaces(css) {
  const faces = [];
  const blocks = css.split("@font-face").slice(1);
  for (const block of blocks) {
    const body = block.slice(0, block.indexOf("}"));
    const family = (body.match(/font-family:\s*'([^']+)'/) || [])[1];
    const style = (body.match(/font-style:\s*(\w+)/) || [])[1] || "normal";
    const weight = (body.match(/font-weight:\s*([\d\s]+);/) || [])[1];
    const url = (body.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
    const range = (body.match(/unicode-range:\s*([^;]+);/) || [])[1];
    if (family && weight && url && range && range.indexOf(LATIN_HINT) !== -1) {
      faces.push({ family, style, weight: weight.trim(), url, range: range.trim() });
    }
  }
  return faces;
}

async function get(url) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error("HTTP " + res.status + " for " + url);
  return res;
}

const css = await readFile(CSS_PATH, "utf8");
const existing = css.slice(css.indexOf(START), css.indexOf(END) + END.length);

if (CHECK) {
  const count = (existing.match(/@font-face/g) || []).length;
  console.log(count ? "embedded faces: " + count + " (" + (existing.length / 1024).toFixed(1) + " KB)" : "no embedded fonts");
  process.exit(0);
}

console.log("fetching " + REQUEST);
const sheet = await get(REQUEST).then((r) => r.text());
const faces = parseFaces(sheet);
if (!faces.length) throw new Error("no latin woff2 faces found in the Google Fonts sheet");

let block = START + "\n";
for (const face of faces) {
  const buf = Buffer.from(await get(face.url).then((r) => r.arrayBuffer()));
  const b64 = buf.toString("base64");
  block +=
    "@font-face{font-family:\"" + face.family + "\";font-style:" + face.style + ";font-weight:" + face.weight +
    ";font-display:swap;src:url(data:font/woff2;base64," + b64 + ") format(\"woff2\");" +
    "unicode-range:" + face.range + "}\n";
  console.log("  " + face.family + " " + face.style + " " + face.weight + " — " + (buf.length / 1024).toFixed(1) + " KB");
}
block += END;

let out;
if (existing.length) {
  out = css.replace(existing, block);
} else {
  const at = css.indexOf(":root {");
  if (at === -1) throw new Error("could not find the :root block in css/styles.css");
  out = css.slice(0, at) + block + "\n\n" + css.slice(at);
}
await writeFile(CSS_PATH, out, "utf8");
console.log("embedded " + faces.length + " faces (" + (block.length / 1024).toFixed(1) + " KB) into css/styles.css");
